/**
 * Tests the persistence mapping of {@link TrackedEntityProgramIndicatorDimension} to the
 * trackedentityprogramindicatordimension table, and its use as the element of {@link
 * EventVisualization#getProgramIndicatorDimensions()}.
 */
@Transactional
class TrackedEntityProgramIndicatorDimensionStoreTest extends PostgresIntegrationTestBase {

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private EventVisualizationStore eventVisualizationStore;

  @Autowired private EventVisualizationService eventVisualizationService;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private Program program;

  private ProgramIndicator indicatorA;

  private ProgramIndicator indicatorB;

  private LegendSet legendSet;

  @BeforeEach
  void setUp() {
    program = createProgram('A');
    manager.save(program);
    indicatorA = createProgramIndicator('A', program, "1", null);
    indicatorB = createProgramIndicator('B', program, "1", null);
    manager.save(indicatorA);
    manager.save(indicatorB);
    legendSet = createLegendSet('A');
    manager.save(legendSet);
  }

  @Test
  @DisplayName(
      "the id is generated by a sequence generator on hibernate_sequence, one nextval per id")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
    assertEquals(1, generator.getDatabaseStructure().getIncrementSize());
    assertInstanceOf(NoopOptimizer.class, generator.getOptimizer());
  }

  @Test
  @DisplayName(
      "the program indicator, legend set and filter are written to their columns and read back from them")
  void testColumnsRoundTrip() {
    TrackedEntityProgramIndicatorDimension dimension =
        persist(new TrackedEntityProgramIndicatorDimension(indicatorA, legendSet, "GT:5;LT:10"));

    assertEquals(
        Map.of(
            "programindicatorid", indicatorA.getId(),
            "legendsetid", legendSet.getId(),
            "filter", "GT:5;LT:10"),
        jdbcTemplate.queryForMap(
            "select programindicatorid, legendsetid, filter"
                + " from trackedentityprogramindicatordimension"
                + " where trackedentityprogramindicatordimensionid = ?",
            dimension.getId()));

    clearSessionAndSecondLevelCache();

    TrackedEntityProgramIndicatorDimension reloaded = reload(dimension);
    assertEquals(dimension.getId(), reloaded.getId());
    assertEquals(indicatorA.getUid(), reloaded.getProgramIndicator().getUid());
    assertEquals(legendSet.getUid(), reloaded.getLegendSet().getUid());
    assertEquals("GT:5;LT:10", reloaded.getFilter());
  }

  @Test
  @DisplayName("the program indicator, legend set and filter are optional")
  void testAllPropertiesAreNullable() {
    EntityPersister persister = persister();
    for (String property : List.of("programIndicator", "legendSet", "filter")) {
      assertTrue(
          persister
              .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)],
          property);
    }

    TrackedEntityProgramIndicatorDimension dimension =
        persist(new TrackedEntityProgramIndicatorDimension(null, null, null));
    clearSessionAndSecondLevelCache();

    TrackedEntityProgramIndicatorDimension reloaded = reload(dimension);
    assertNull(reloaded.getProgramIndicator());
    assertNull(reloaded.getLegendSet());
    assertNull(reloaded.getFilter());
  }

  @Test
  @DisplayName("the filter is mapped as text")
  void testFilterIsText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("filter"));
  }

  @Test
  @DisplayName("the program indicator and legend set are loaded lazily")
  void testAssociationsAreLazy() {
    for (String property : List.of("programIndicator", "legendSet")) {
      ManyToOneType type =
          assertInstanceOf(ManyToOneType.class, persister().getPropertyType(property));
      assertFalse(type.isEager(null), property);
    }
  }

  @Test
  @DisplayName(
      "an event visualization saves its program indicator dimensions by cascade and keeps their order")
  void testEventVisualizationOwnsOrderedDimensions() {
    EventVisualization eventVisualization = createEventVisualization('A', program);
    eventVisualization
        .getProgramIndicatorDimensions()
        .add(new TrackedEntityProgramIndicatorDimension(indicatorB, null, "EQ:1"));
    eventVisualization
        .getProgramIndicatorDimensions()
        .add(new TrackedEntityProgramIndicatorDimension(indicatorA, legendSet, null));
    eventVisualizationStore.save(eventVisualization);
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    List<TrackedEntityProgramIndicatorDimension> reloaded =
        eventVisualizationStore
            .getByUid(eventVisualization.getUid())
            .getProgramIndicatorDimensions();
    assertEquals(
        List.of(indicatorB.getUid() + ":EQ:1", indicatorA.getUid() + ":null"),
        reloaded.stream()
            .map(d -> d.getProgramIndicator().getUid() + ":" + d.getFilter())
            .toList());
  }

  @Test
  @DisplayName(
      "the store HQL that joins program indicator dimensions on their program indicator finds only the event"
          + " visualizations with a dimension of that program indicator")
  void testAnalyticalObjectsByProgramIndicatorDimension() {
    EventVisualization withA = createEventVisualization('A', program);
    withA
        .getProgramIndicatorDimensions()
        .add(new TrackedEntityProgramIndicatorDimension(indicatorA, null, null));
    EventVisualization withB = createEventVisualization('B', program);
    withB
        .getProgramIndicatorDimensions()
        .add(new TrackedEntityProgramIndicatorDimension(indicatorB, null, null));
    eventVisualizationStore.save(withA);
    eventVisualizationStore.save(withB);
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    assertEquals(
        List.of(withA.getUid()),
        eventVisualizationService.getAnalyticalObjectsByDataDimension(indicatorA).stream()
            .map(EventVisualization::getUid)
            .toList());
  }

  /** Reloads must hit the database, not the second-level cache. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(TrackedEntityProgramIndicatorDimension.class);
  }

  private TrackedEntityProgramIndicatorDimension persist(
      TrackedEntityProgramIndicatorDimension dimension) {
    entityManager.persist(dimension);
    entityManager.flush();
    return dimension;
  }

  private TrackedEntityProgramIndicatorDimension reload(
      TrackedEntityProgramIndicatorDimension dimension) {
    return entityManager.find(TrackedEntityProgramIndicatorDimension.class, dimension.getId());
  }
}
