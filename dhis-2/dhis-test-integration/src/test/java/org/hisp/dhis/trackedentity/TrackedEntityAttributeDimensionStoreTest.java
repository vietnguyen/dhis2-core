import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/**
 * Tests the persistence mapping of {@link TrackedEntityAttributeDimension} to the
 * trackedentityattributedimension table, and its use as the element of {@link
 * EventVisualization#getAttributeDimensions()}.
 */
@Transactional
class TrackedEntityAttributeDimensionStoreTest extends PostgresIntegrationTestBase {

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private EventVisualizationStore eventVisualizationStore;

  @Autowired private EventVisualizationService eventVisualizationService;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private Program program;

  private TrackedEntityAttribute attributeA;

  private TrackedEntityAttribute attributeB;

  private LegendSet legendSet;

  @BeforeEach
  void setUp() {
    program = createProgram('A');
    manager.save(program);
    attributeA = createTrackedEntityAttribute('A');
    attributeB = createTrackedEntityAttribute('B');
    manager.save(attributeA);
    manager.save(attributeB);
    legendSet = createLegendSet('A');
    manager.save(legendSet);
  }

  @Test
  @DisplayName(
      "the id is generated by a sequence generator on hibernate_sequence, one nextval per id")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
    assertEquals(1, generator.getDatabaseStructure().getIncrementSize());
    assertInstanceOf(NoopOptimizer.class, generator.getOptimizer());
  }

  @Test
  @DisplayName(
      "the attribute, legend set and filter are written to their columns and read back from them")
  void testColumnsRoundTrip() {
    TrackedEntityAttributeDimension dimension =
        persist(new TrackedEntityAttributeDimension(attributeA, legendSet, "GT:5;LT:10"));

    assertEquals(
        Map.of(
            "trackedentityattributeid", attributeA.getId(),
            "legendsetid", legendSet.getId(),
            "filter", "GT:5;LT:10"),
        jdbcTemplate.queryForMap(
            "select trackedentityattributeid, legendsetid, filter"
                + " from trackedentityattributedimension"
                + " where trackedentityattributedimensionid = ?",
            dimension.getId()));

    clearSessionAndSecondLevelCache();

    TrackedEntityAttributeDimension reloaded = reload(dimension);
    assertEquals(dimension.getId(), reloaded.getId());
    assertEquals(attributeA.getUid(), reloaded.getAttribute().getUid());
    assertEquals(legendSet.getUid(), reloaded.getLegendSet().getUid());
    assertEquals("GT:5;LT:10", reloaded.getFilter());
  }

  @Test
  @DisplayName("the attribute, legend set and filter are optional")
  void testAllPropertiesAreNullable() {
    EntityPersister persister = persister();
    for (String property : List.of("attribute", "legendSet", "filter")) {
      assertTrue(
          persister
              .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)],
          property);
    }

    TrackedEntityAttributeDimension dimension =
        persist(new TrackedEntityAttributeDimension(null, null, null));
    clearSessionAndSecondLevelCache();

    TrackedEntityAttributeDimension reloaded = reload(dimension);
    assertNull(reloaded.getAttribute());
    assertNull(reloaded.getLegendSet());
    assertNull(reloaded.getFilter());
  }

  @Test
  @DisplayName("the filter is mapped as text")
  void testFilterIsText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("filter"));
  }

  @Test
  @DisplayName("the attribute and legend set are loaded lazily")
  void testAssociationsAreLazy() {
    for (String property : List.of("attribute", "legendSet")) {
      ManyToOneType type =
          assertInstanceOf(ManyToOneType.class, persister().getPropertyType(property));
      assertFalse(type.isEager(null), property);
    }
  }

  @Test
  @DisplayName(
      "an event visualization saves its attribute dimensions by cascade, keeps their order and is"
          + " found by the HQL that joins them on the attribute")
  void testEventVisualizationOwnsOrderedDimensions() {
    EventVisualization eventVisualization = createEventVisualization('A', program);
    eventVisualization
        .getAttributeDimensions()
        .add(new TrackedEntityAttributeDimension(attributeB, null, "EQ:1"));
    eventVisualization
        .getAttributeDimensions()
        .add(new TrackedEntityAttributeDimension(attributeA, legendSet, null));
    eventVisualizationStore.save(eventVisualization);
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    List<TrackedEntityAttributeDimension> reloaded =
        eventVisualizationStore.getByUid(eventVisualization.getUid()).getAttributeDimensions();
    assertEquals(
        List.of(attributeB.getUid() + ":EQ:1", attributeA.getUid() + ":null"),
        reloaded.stream().map(d -> d.getAttribute().getUid() + ":" + d.getFilter()).toList());

    assertEquals(
        List.of(eventVisualization.getUid()),
        eventVisualizationService.getAnalyticalObjectsByDataDimension(attributeA).stream()
            .map(EventVisualization::getUid)
            .toList());
  }

  /** Reloads must hit the database, not the second-level cache. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(TrackedEntityAttributeDimension.class);
  }

  private TrackedEntityAttributeDimension persist(TrackedEntityAttributeDimension dimension) {
    entityManager.persist(dimension);
    entityManager.flush();
    return dimension;
  }

  private TrackedEntityAttributeDimension reload(TrackedEntityAttributeDimension dimension) {
    return entityManager.find(TrackedEntityAttributeDimension.class, dimension.getId());
  }
}
